        <h6 class="fw-bold">Overview</h6>
        <p class="text-justify">
          LBJ Tropical Medical Center in Faga’alu, Tutuila, is the only hospital in American Samoa. A 2019 assessment for the US Department of the Interior, prepared by the US Army Corps of Engineers, described it as a 128-bed general acute care hospital and “the only full-service healthcare facility in the territory.” Its services include inpatient paediatrics, maternity, surgery and medicine, a neonatal intensive care unit and an intensive care unit, operating and labour and delivery rooms, dialysis, mental health, pharmacy, dental and physical therapy. LBJ TMC’s own website describes it as a 150-bed facility, and HRSA lists it as licensed for 150 beds.
        </p>
        <p class="text-justify">
          <strong>Note:</strong> Record LBJ TMC as “Hospital — public authority (ASMCA), general acute care.” Bed figures differ between sources (128 staffed beds in the 2019 assessment; 150 licensed beds on the hospital’s website and HRSA). The 2019 assessment warned that continued deterioration of the building could lead to denial of accreditation, so check current CMS certification status.
        </p>

        <h6 class="fw-bold">Role</h6>
        <ul>
          <li>Serve as the only inpatient hospital and emergency department in the territory</li>
          <li>Receive referrals from DOH community health centers</li>
          <li>Arrange off-island referrals for care not available locally.</li>
        </ul>

        <h6 class="fw-bold">Clinical Services</h6>
        <p class="mb-1"><strong>Core Capability Areas</strong></p>
        <ul>
          <li>Medicine, surgery, maternity, paediatrics, ICU and NICU, dialysis, mental health, dental and physical therapy</li>
        </ul>
        <p class="mb-1"><strong>Typical Bed Capacity</strong></p>
        <ul>
          <li>128 beds (2019 assessment); 150 licensed beds (LBJ TMC; HRSA)</li>
