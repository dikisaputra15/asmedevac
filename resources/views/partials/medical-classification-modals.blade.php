        <h6 class="fw-bold">Overview</h6>
        <p class="text-justify">
          The DOH runs a network of community health centers, known collectively as the AS Community Health Centers. The Pacific Basin Telehealth Resource Center reports six centers: four on the main island of Tutuila and two in the Manu’a Islands (on Ofu and Ta’u). DOH clinics provide primary care, dental care, women’s health, pharmacy, behavioral health, well-baby care, nutrition services and drug and alcohol testing. A satellite pharmacy at the Tafuna health center is run jointly with the LBJ TMC pharmacy.
        </p>
        <p class="text-justify">
          <strong>Note:</strong> No law defines a “community health center” as a facility class. Record these as “Community Health Center — public (DOH).” The Manu’a centers are the only health facilities on those islands and transfer serious cases to LBJ TMC on Tutuila.
        </p>

